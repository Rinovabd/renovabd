/** Rinovabd v2 only: copy all public campaign assets to the freshly created v2 R2 bucket and generate frontend-safe API URLs. */
import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const base = "https://api-v2.rinovabd.com";
const token = (await readFile("/home/ubuntu/.rinovabd-v2/admin-access-token.txt", "utf8")).trim();
const assetsDirectory = "/home/ubuntu/webdev-static-assets";
const outputPath = fileURLToPath(new URL("../../client/src/lib/cloudflare-assets.ts", import.meta.url));
const inventory = [
  { alias: "heroRitual", objectName: "hero-ritual", filename: "rinovabd-hero-ritual.png" },
  { alias: "productEssentials", objectName: "product-essentials", filename: "rinovabd-product-pink-essentials.png" },
  { alias: "collectionFace", objectName: "collection-face", filename: "rinovabd-collection-face.png" },
  { alias: "adminStilllife", objectName: "admin-stilllife", filename: "rinovabd-admin-stilllife.png" },
  { alias: "ribbonLoopSymbol", objectName: "ribbon-loop-symbol", filename: "rinovabd-ribbon-loop-symbol.png" },
  { alias: "shopEditorialRibbon", objectName: "shop-editorial-ribbon", filename: "rinovabd-shop-editorial-ribbon.png" },
  { alias: "shopBeautyCrop", objectName: "shop-beauty-crop", filename: "rinovabd-shop-beauty-crop.png" },
];
const contentType = (filename) => filename.endsWith(".png") ? "image/png" : filename.endsWith(".webp") ? "image/webp" : "image/jpeg";
const extension = (filename) => filename.split(".").at(-1).toLowerCase();

const login = await fetch(`${base}/api/admin/login`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ token }) });
assert.equal(login.status, 200, "The v2 admin token could not open an upload session.");
const { session } = await login.json();
const published = {};
for (const { alias, objectName, filename } of inventory) {
  const bytes = await readFile(`${assetsDirectory}/${filename}`);
  const key = `site/v2/${objectName}.${extension(filename)}`;
  const response = await fetch(`${base}/api/media`, { method: "POST", headers: { "x-admin-session": session, "content-type": contentType(filename), "x-filename": filename, "x-object-key": key }, body: bytes });
  assert.equal(response.status, 201, `Asset upload failed: ${filename}`);
  const { asset } = await response.json();
  published[alias] = `${base}${asset.url}`;
}

const catalogue = await fetch(`${base}/api/admin/products`, { headers: { "x-admin-session": session } });
assert.equal(catalogue.status, 200, "The v2 admin catalogue could not be read.");
const productAssets = { "rnv-001": published.productEssentials, "rnv-002": published.heroRitual, "rnv-003": published.collectionFace, "rnv-004": published.shopEditorialRibbon };
for (const product of (await catalogue.json()).products) {
  const image = productAssets[product.id]; if (!image) continue;
  const update = await fetch(`${base}/api/admin/products/${encodeURIComponent(product.id)}`, { method: "PATCH", headers: { "x-admin-session": session, "content-type": "application/json" }, body: JSON.stringify({ ...product, image }) });
  assert.equal(update.status, 200, `Catalogue image migration failed: ${product.id}`);
}

await writeFile(outputPath, `/** Ribbon Modernism: Cloudflare v2 R2 asset URLs generated by the authenticated deployment publisher. */\nexport const cloudflareAssets = ${JSON.stringify(published, null, 2)} as const;\n`);
